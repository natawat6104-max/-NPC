def thai(clip, prefix):
    if clip in OVERRIDE:
        return OVERRIDE[clip]
    body = clip[len(prefix) + 1:] if prefix and clip.startswith(prefix + '_') else clip
    s = ' ' + body.replace('_', ' ') + ' '
    s = re.sub(r' v (\d) ', r' \1 ', s).replace(' standard ', ' ')
    # trailing variant number -> (แบบ n)
    var = ''
    m = re.search(r' (\d{1,2}) $', s)
    if m and m[1] not in ('45', '90', '180'):
        n = int(m[1]); s = s[:m.start()] + ' '
        if n > 1: var = f' (แบบ {n})'
    for pat, rep in PHRASES:
        s = re.sub(pat, rep, s)
    toks = []
    for t in s.split():
        toks.append(WORDS.get(t, t))
    txt = ' '.join(t for t in toks if t)
    txt = re.sub(r'จาก (ด้านหน้า|จากข้างหลัง|ซ้าย|ขวา)', lambda m: 'จาก' + m[1].replace('จาก', ''), txt)
